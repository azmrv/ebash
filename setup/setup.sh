#!/bin/bash
#
# Главный скрипт интерактивного меню установки окружения разработчика
# Запуск: ./setup.sh
#
# Получаем абсолютный путь к директории, где находится сам скрипт
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# Подключаем общие функции (теперь путь абсолютный и надёжный)
source "$SCRIPT_DIR/scripts/common.sh"

show_menu() {
    echo -e "${GREEN}=== ИНТЕРАКТИВНОЕ МЕНЮ УСТАНОВКИ ОКРУЖЕНИЯ ===${NC}"
    echo "1. Установка системного ПО (требует ввода пароля sudo)"
    echo "2. Установка инструментов разработки (Node.js, Go, VS Code, Git)"
    echo "3. Восстановление пользовательских конфигураций (configs)"
    echo "4. ПОЛНАЯ УСТАНОВКА (Автоматический пошаговый цикл)"
    echo "5. Пересоздать структуру служебных папок"
    echo "0. Выход"
    echo
    read -p "Выберите вариант [0-5]: " choice
}

# Создаём структуру папок при первом запуске
create_structure
clear

while true; do
    show_menu
    case $choice in
        1)
            info "Запуск установки системного ПО..."
            sudo "$SCRIPT_DIR/install_system_software.sh"
            ;;
        2)
            info "Запуск установки инструментов разработки..."
            "$SCRIPT_DIR/setup_dev_env.sh"
            ;;
        3)
            info "Запуск восстановления конфигураций..."
            "$SCRIPT_DIR/restore_configs.sh"
            ;;
        4)
            warn "ВНИМАНИЕ: Полная установка требует разделения на этапы!"
            echo "Этап 1: Установка системного ПО (Docker, утилиты) -> Требуется REBOOT."
            echo "Этап 2: Инструменты разработки и конфигурации (запускается после перезагрузки)."
            echo ""
            read -p "Запустить Этап 1 (Системное ПО)? (y/n): " -n 1 -r
            echo
            if [[ $REPLY =~ ^[Yy]$ ]]; then
                sudo "$SCRIPT_DIR/install_system_software.sh"
                echo ""
                warn "🛑 СИСТЕМНЫЙ ЭТАП ЗАВЕРШЕН!"
                warn "ОБЯЗАТЕЛЬНО ПЕРЕЗАГРУЗИТЕ СИСТЕМУ: sudo reboot"
                warn "После перезагрузки запустите ./setup.sh снова и выберите пункты 2 и 3."
                exit 0
            fi
            ;;
        5)
            create_structure
            ;;
        0)
            info "Выход из установщика. Удачной разработки!"
            exit 0
            ;;
        *)
            error "Неверный выбор! Пожалуйста, укажите цифру от 0 до 5."
            ;;
    esac
    
    echo
    read -p "Нажмите Enter, чтобы вернуться в меню..."
    clear
done